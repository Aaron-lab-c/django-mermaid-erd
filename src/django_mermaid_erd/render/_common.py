DIRECTION_CHOICES = ("TB", "BT", "LR", "RL")


def banner_text() -> str:
    from .. import __version__

    return "generated by django-mermaid-erd %s - do not edit by hand" % __version__


def attribute_name(attr: Attribute, field_names: str) -> str:
    return attr.column if field_names == "attname" else attr.name


def attribute_type(attr: Attribute, types: str) -> str:
    if types == "none":
        return NO_TYPE
    if types == "full" and attr.type_params:
        return "%s(%s)" % (attr.type, attr.type_params)
    return attr.type


def visible_attributes(
    entity: Entity,
    fields: str,
    field_names: str,
    sort_fields: bool,
    max_fields: Optional[int],
) -> Tuple[List[Attribute], int]:
    """Return ``(attributes to show, number hidden by max_fields)``."""
    if fields == "none":
        return [], 0
    attrs = list(entity.attributes)
    if fields == "keys":
        attrs = [a for a in attrs if a.is_key]
    if sort_fields:
        attrs.sort(key=lambda a: attribute_name(a, field_names))
    hidden = 0
    if max_fields is not None and len(attrs) > max_fields:
        hidden = len(attrs) - max_fields
        attrs = attrs[:max_fields]
    return attrs, hidden


def comment_parts(attr: Attribute, present_labels, comments: bool, verbose_names: bool) -> List[str]:
    parts = []
    if attr.nullable:
        parts.append("nullable")
    if comments and attr.choices:
        parts.append("choices")
    if attr.comment:
        parts.append(attr.comment)
    if verbose_names and attr.verbose_name:
        parts.append(attr.verbose_name)
    if attr.references and attr.references not in present_labels:
        parts.append("-> %s" % attr.references)
    return parts


def more_fields_note(hidden: int) -> str:
    return "%%%% +%d more field%s" % (hidden, "" if hidden == 1 else "s")


def entities_by_app(schema: Schema):
    for app in schema.apps:
        yield app, [e for e in schema.entities if e.app_label == app]
