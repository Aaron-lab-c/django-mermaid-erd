def _non_negative(value: str) -> int:
    import argparse

    try:
        number = int(value)
    except ValueError:
        raise argparse.ArgumentTypeError("expected an integer, got %r" % value) from None
    if number < 0:
        raise argparse.ArgumentTypeError("must be >= 0")
    return number


def add_arguments(parser) -> None:
    """Add every option. Defaults are ``None`` so settings can fill unset ones."""
    parser.add_argument(
        "targets",
        nargs="*",
        metavar="TARGET",
        help="app label or app_label.ModelName; default: every non-django.contrib app",
    )

    sel = parser.add_argument_group("selection")
    sel.add_argument(
        "-e",
        "--exclude",
        action="append",
        metavar="PATTERN",
        help="exclude an app or app.Model; glob patterns allowed (shop.*Log); repeatable",
    )
    sel.add_argument(
        "--include-builtin",
        action="store_true",
        default=None,
        help="include django.contrib.* apps (auth, contenttypes, sessions, admin, ...)",
    )
    sel.add_argument("--no-proxy", dest="proxy", action="store_false", default=None, help="leave out proxy models")
    sel.add_argument("--focus", metavar="APP.MODEL", help="only draw this model and its neighbours")
    sel.add_argument("--depth", type=_non_negative, metavar="N", help="neighbour distance for --focus (default 1)")

    content = parser.add_argument_group("content")
    content.add_argument("-d", "--diagram", choices=DIAGRAMS, help="diagram type (default er)")
    content.add_argument("--fields", choices=FIELDS_CHOICES, help="which attributes to list (default all)")
    content.add_argument("--types", choices=TYPES_CHOICES, help="attribute types (default short)")
    content.add_argument(
        "--field-names", choices=FIELD_NAMES_CHOICES, help="customer_id (attname, default) or customer (name)"
    )
    content.add_argument("--sort-fields", action="store_true", default=None, help="list attributes alphabetically")
    content.add_argument("--max-fields", type=_non_negative, metavar="N", help="show at most N attributes per model")
    content.add_argument(
        "--comments", action="store_true", default=None, help="annotate choices / unmanaged / proxy"
    )
    content.add_argument(
        "--verbose-names", action="store_true", default=None, help="add explicit verbose_name to attribute comments"
    )
    content.add_argument(
        "--generic-edges", action="store_true", default=None, help="draw GenericForeignKey edges to ContentType"
    )
    content.add_argument(
        "--qualified", action="store_true", default=None, help="name every entity app_Model, not only clashing ones"
    )
    content.add_argument("--direction", choices=DIRECTION_CHOICES, help="layout direction")
    content.add_argument(
        "--no-banner", dest="banner", action="store_false", default=None, help="omit the 'generated by' comment"
    )
    content.add_argument(
        "--group-by-app",
        dest="group_by_app",
        action="store_true",
        default=None,
        help="class diagram: wrap each app in a namespace (default)",
    )
    content.add_argument(
        "--no-group-by-app", dest="group_by_app", action="store_false", help="class diagram: no namespaces"
    )

    out = parser.add_argument_group("output")
    out.add_argument("-o", "--output", metavar="FILE", help="write to FILE instead of stdout")
    out.add_argument(
        "--md", action="store_true", default=None, help="wrap in a ```mermaid fence (automatic for -o *.md)"
    )
    out.add_argument(
        "--inject",
        metavar="FILE",
        help="replace the <!-- mermaid-erd:start/end --> block in FILE (appended if missing)",
    )
    out.add_argument(
        "--check",
        action="store_true",
        default=None,
        help="don't write; exit 1 with a diff if -o / --inject targets are out of date",
    )
    out.add_argument("--svg", metavar="FILE", help="also render an SVG image")
    out.add_argument("--png", metavar="FILE", help="also render a PNG image")
    out.add_argument("--renderer", choices=RENDERER_CHOICES, help="image renderer (default auto)")


def build(opts: Options):
    """Select models and build the (optionally focused) schema."""
    models = select_models(
        opts.targets,
        exclude=opts.exclude,
        include_builtin=opts.include_builtin,
        include_proxy=opts.proxy,
    )
    if not models:
        raise MermaidErdError("no models selected (check your targets and --exclude patterns)")
    schema = build_schema(models, qualified=opts.qualified, generic_edges=opts.generic_edges)
    if opts.focus:
        model = find_model(opts.focus)
        key = entity_key_for(schema, model_label(model))
        if key is None:
            raise MermaidErdError(
                "--focus model '%s' is not among the selected models "
                "(name its app as a target or use --include-builtin)" % model_label(model)
            )
        schema = focus_schema(schema, key, opts.depth)
    return schema


def generate_text(opts: Options) -> str:
    return render(build(opts), opts.diagram, **opts.render_options())


def _output_text(opts: Options, text: str) -> str:
    md = opts.md
    if md is None:
        md = bool(opts.output) and opts.output.lower().endswith((".md", ".markdown"))
    return wrap_markdown(text) if md else text


def run(opts: Options, stdout, stderr) -> int:
    """Execute with resolved options. Raises :class:`MermaidErdError` on user errors."""
    if opts.check and not (opts.output or opts.inject):
        raise MermaidErdError("--check needs a target to compare: pass -o/--output and/or --inject")

    text = generate_text(opts)

    targets = []
    if opts.output:
        targets.append((opts.output, lambda current: _output_text(opts, text)))
    if opts.inject:
        targets.append((opts.inject, lambda current: inject(current, text)))

    if opts.check:
        stale = []
        for path, expected_for in targets:
            current = read_text(path)
            lines = diff(current, expected_for(current), path)
            if lines:
                stdout.write("".join(lines))
                stale.append(path + (" (missing)" if current is None else ""))
        if stale:
            raise CheckFailed(
                "ER diagram is out of date: %s. Re-run without --check to update." % ", ".join(stale)
            )
        stderr.write("ER diagram is up to date: %s\n" % ", ".join(p for p, _ in targets))
        return 0

    for path, expected_for in targets:
        current = read_text(path)
        new = expected_for(current)
        if current == new:
            stderr.write("Unchanged %s\n" % path)
        else:
            write_text(path, new)
            stderr.write("Wrote %s\n" % path)

    for fmt in ("svg", "png"):
        path = getattr(opts, fmt)
        if path:
            from .image import render_image

            used = render_image(text, path, fmt, opts.renderer, warn=lambda msg: stderr.write(msg + "\n"))
            stderr.write("Wrote %s (via %s)\n" % (path, used))

    if not (targets or opts.svg or opts.png):
        stdout.write(_output_text(opts, text))
    return 0


def ensure_utf8_stdout(stream=None) -> None:
    """Emit UTF-8 with LF line endings when stdout is piped/redirected (Windows defaults differ)."""
    stream = stream if stream is not None else sys.stdout
    reconfigure = getattr(stream, "reconfigure", None)
    isatty = getattr(stream, "isatty", None)
    if reconfigure is None or (isatty is not None and isatty()):
        return
    try:
        reconfigure(encoding="utf-8", newline="\n")
    except (ValueError, OSError):  # pragma: no cover - stream already used / detached
        pass
