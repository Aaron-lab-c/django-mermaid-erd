import random

from django_mermaid_erd import render
from django_mermaid_erd.render import render_er
from django_mermaid_erd.schema import Schema

from .helpers import attr, entity, mini_schema, reserved_schema


def body(text):
    return [line.strip() for line in text.splitlines()]


def test_header_and_banner():
    lines = render_er(mini_schema()).splitlines()
    assert lines[0] == "erDiagram"
    assert lines[1].startswith("    %% generated by django-mermaid-erd ")
    assert "%% generated" not in render_er(mini_schema(), banner=False)


def test_relation_lines():
    lines = body(render_er(mini_schema()))
    assert 'Parent ||--o{ Child : "parent"' in lines
    assert 'Parent |o--o{ Child : "maybe"' in lines
    assert 'Child ||--|| Twin : "child"' in lines
    assert 'Parent |o--|| Twin : "opt"' in lines
    assert 'Child }o--o{ Twin : "friends"' in lines
    assert 'Child }o--o{ Twin : "others via app.Link"' in lines
    assert 'Parent ||--|| Sub : "inherits"' in lines
    assert 'Parent ||..|| Alias : "proxy"' in lines
    assert 'Parent |o..o{ Tagged : "content_object"' in lines
    assert 'Parent |o--o{ Parent : "up"' in lines


def test_attribute_lines_keys_and_comments():
    lines = body(render_er(mini_schema()))
    assert "int id PK" in lines
    assert "int parent_id FK" in lines
    assert 'int maybe_id FK "nullable"' in lines
    assert 'int ext_id FK "-> other.Gone"' in lines  # target not in diagram
    assert "int child_id FK, UK" in lines
    assert "string note \"say 'hi'\"" in lines
    assert "decimal price" in lines


def test_comments_and_verbose_names():
    lines = body(render_er(mini_schema(), comments=True, verbose_names=True))
    assert 'decimal price "choices, 價格"' in lines
    assert "%% app.Alias: unmanaged" in lines


def test_types_modes():
    assert "decimal(10,2) price" in body(render_er(mini_schema(), types="full"))
    assert "string(20) note \"say 'hi'\"" in body(render_er(mini_schema(), types="full"))
    lines = body(render_er(mini_schema(), types="none"))
    assert "field id PK" in lines and "field price" in lines


def test_field_names_and_sorting():
    lines = body(render_er(mini_schema(), field_names="name", sort_fields=True))
    child = lines[lines.index("Child {") + 1 : lines.index("Child {") + 7]
    assert [line.split()[1] for line in child] == sorted(["id", "parent", "maybe", "ext", "note", "price"])


def test_fields_keys_and_none():
    keys = body(render_er(mini_schema(), fields="keys"))
    assert "string note \"say 'hi'\"" not in keys and "int parent_id FK" in keys
    none = render_er(mini_schema(), fields="none")
    assert "{" not in none.split("\n\n")[0].replace("o{", "")
    assert "    Child\n" in none


def test_max_fields():
    text = render_er(mini_schema(), max_fields=2)
    assert "    %% +4 more fields\n" in text
    single = Schema([entity("A", attrs=[attr("a"), attr("b")])], [], []).normalized()
    assert "%% +1 more field\n" in render_er(single, max_fields=1)


def test_entity_without_attributes_is_bare():
    assert "\n    Sub\n" in render_er(mini_schema())


def test_alias_for_prefixed_keys():
    schema = Schema([entity("shop_Tag", app="shop", model="Tag")], [], []).normalized()
    assert '    shop_Tag["shop.Tag"]\n' in render_er(schema)


def test_reserved_words_escaped():
    text = render_er(reserved_schema())
    assert 'Class_["Class"] {' in text
    assert 'Style_["Style"] {' in text
    assert "    Note {" in text  # not reserved in erDiagram
    assert "int `fk`" in text and "int `uk` UK" in text
    assert 'o ||--o{ Class_ : "class"' in text


def test_label_quotes_escaped():
    from django_mermaid_erd.schema import Relation

    schema = Schema([entity("A"), entity("B")], [Relation("B", "A", "fk", 'say "x"')], []).normalized()
    assert 'A ||--o{ B : "say #quot;x#quot;"' in render_er(schema)


def test_direction():
    assert "    direction LR\n" in render_er(mini_schema(), direction="LR")
    assert "direction" not in render_er(mini_schema())


def test_whitespace_rules():
    text = render_er(mini_schema())
    assert text.endswith("\n") and not text.endswith("\n\n")
    assert all(line == line.rstrip() for line in text.splitlines())
    assert "\t" not in text


def test_deterministic_under_shuffle():
    base = mini_schema()
    expected = render_er(base)
    for seed in range(10):
        rng = random.Random(seed)
        entities, relations = list(base.entities), list(base.relations)
        rng.shuffle(entities)
        rng.shuffle(relations)
        assert render_er(Schema(entities, relations, [])) == expected


def test_render_dispatch():
    assert render(mini_schema()) == render_er(mini_schema())
    assert render(mini_schema(), "er", group_by_app=True) == render_er(mini_schema())
    assert render(mini_schema(), "class").startswith("classDiagram\n")
