import random

from django_mermaid_erd.render import render_class
from django_mermaid_erd.schema import Schema

from .helpers import entity, mini_schema, reserved_schema


def body(text):
    return [line.strip() for line in text.splitlines()]


def test_namespaces_and_members():
    text = render_class(mini_schema())
    assert text.startswith("classDiagram\n    %% generated by")
    assert "    namespace app {\n        class Alias\n" in text
    assert "        class Child {\n            +int id\n" in text
    assert "+int parent_id" in text
    assert "        class Sub\n" in text


def test_relations():
    lines = body(render_class(mini_schema()))
    assert 'Parent "1" --> "*" Child : parent' in lines
    assert 'Parent "0..1" --> "*" Child : maybe' in lines
    assert 'Child "1" --> "1" Twin : child' in lines
    assert 'Parent "0..1" --> "1" Twin : opt' in lines
    assert 'Child "*" -- "*" Twin : friends' in lines
    assert 'Child "*" -- "*" Twin : others via app.Link' in lines
    assert "Parent <|-- Sub" in lines
    assert "Parent <|.. Alias : proxy" in lines
    assert 'Parent "0..1" ..> "*" Tagged : content_object' in lines


def test_full_types_downgraded_to_short():
    assert "+decimal price" in render_class(mini_schema(), types="full")


def test_types_none():
    assert "+price" in body(render_class(mini_schema(), types="none"))


def test_flat_and_annotations():
    text = render_class(mini_schema(), group_by_app=False, comments=True)
    assert "namespace" not in text
    assert "    %% app: app\n" in text
    assert "    class Alias {\n        <<proxy>>\n        <<unmanaged>>\n    }\n" in text


def test_fields_none_and_keys():
    assert "+" not in render_class(mini_schema(), fields="none").split("\n\n")[0]
    keys = render_class(mini_schema(), fields="keys")
    assert "+string note" not in keys and "+int parent_id" in keys


def test_reserved_names():
    text = render_class(reserved_schema())
    assert "namespace note_ {" in text and "namespace link_ {" in text and "namespace click_ {" in text
    assert 'class o_["o"]' in text and 'class call_["call"]' in text
    assert "class Note {" in text  # case-sensitive lexer: CapWords are fine
    assert 'call_ "*" -- "*" Class : style' in text


def test_namespace_never_equals_a_class_id():
    schema = Schema([entity("shop", app="shop")], [], []).normalized()
    assert "namespace shop_ {" in render_class(schema)


def test_deterministic_under_shuffle():
    base = mini_schema()
    expected = render_class(base)
    rng = random.Random(1)
    for _ in range(5):
        entities, relations = list(base.entities), list(base.relations)
        rng.shuffle(entities)
        rng.shuffle(relations)
        assert render_class(Schema(entities, relations, [])) == expected
